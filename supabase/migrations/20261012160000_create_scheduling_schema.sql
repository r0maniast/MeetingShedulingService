-- Persistent storage for the Telegram meeting-scheduling bot.
-- Telegram identifiers are BIGINT because they do not fit safely in INTEGER.

create table public.telegram_users (
    telegram_user_id bigint primary key,
    display_name text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table public.telegram_chats (
    telegram_chat_id bigint primary key,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- A user is enrolled independently in each group chat.
create table public.chat_participants (
    telegram_chat_id bigint not null references public.telegram_chats (telegram_chat_id) on delete cascade,
    telegram_user_id bigint not null references public.telegram_users (telegram_user_id) on delete cascade,
    joined_at timestamptz not null default now(),
    primary key (telegram_chat_id, telegram_user_id)
);

-- A row means that the participant marked the date as free.
create table public.participant_availability (
    telegram_chat_id bigint not null,
    telegram_user_id bigint not null,
    available_on date not null,
    created_at timestamptz not null default now(),
    primary key (telegram_chat_id, telegram_user_id, available_on),
    foreign key (telegram_chat_id, telegram_user_id)
        references public.chat_participants (telegram_chat_id, telegram_user_id)
        on delete cascade
);

create table public.game_sessions (
    id bigint generated by default as identity primary key,
    telegram_chat_id bigint not null references public.telegram_chats (telegram_chat_id) on delete cascade,
    scheduled_for date not null,
    title text not null,
    created_at timestamptz not null default now(),
    unique (telegram_chat_id, scheduled_for)
);

-- Supports finding the free dates of all participants in one chat.
create index participant_availability_chat_date_idx
    on public.participant_availability (telegram_chat_id, available_on);

create index game_sessions_chat_date_idx
    on public.game_sessions (telegram_chat_id, scheduled_for);

create function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create trigger telegram_users_set_updated_at
before update on public.telegram_users
for each row execute function public.set_updated_at();

create trigger telegram_chats_set_updated_at
before update on public.telegram_chats
for each row execute function public.set_updated_at();

-- The backend connects using the database role; browser clients are not granted access.
alter table public.telegram_users enable row level security;
alter table public.telegram_chats enable row level security;
alter table public.chat_participants enable row level security;
alter table public.participant_availability enable row level security;
alter table public.game_sessions enable row level security;
